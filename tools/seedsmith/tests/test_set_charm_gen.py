class CellOccupancyTests(unittest.TestCase):
    def test_the_median_cell_occupancy_over_capability_plus_higher_thresholds_is_at_most_two(self) -> None:
        report = cells.cell_report(SHIPPED_SETS)
        self.assertGreater(report.cells, 0)
        self.assertLessEqual(report.median, TUNING.median_cell_occupancy_max)

    def test_the_cell_key_is_the_capability_plus_the_higher_threshold_multiset(self) -> None:
        entry = {"thresholds": [
            {"pieces": 2, "capability": {"family": "atom.econ-muster"}},
            {"pieces": 3, "atoms": [{"family": "atom.might"}]},
            {"pieces": 4, "atoms": [{"family": "atom.vitality"}, {"family": "atom.ferocity"}]},
        ]}
        self.assertEqual(cells.cell_key(entry),
                         ("atom.econ-muster", ("atom.ferocity", "atom.might", "atom.vitality")))

    def test_two_sets_with_the_same_capability_but_different_stats_are_different_cells(self) -> None:
        """This is the whole argument: the capability is the coarse axis. Keyed on it alone these
        two collide; keyed on the cell they do not."""
        base = {"thresholds": [{"pieces": 2, "capability": {"family": "atom.x"}},
                               {"pieces": 4, "atoms": [{"family": "atom.might"}]}]}
        other = {"thresholds": [{"pieces": 2, "capability": {"family": "atom.x"}},
                                {"pieces": 4, "atoms": [{"family": "atom.vitality"}]}]}
        self.assertNotEqual(cells.cell_key(base), cells.cell_key(other))
        self.assertEqual(cells.cell_report([base, other]).cells, 2)

    def test_capability_usage_is_reported_and_does_not_gate(self) -> None:
        findings = self._run_metric()
        usage = [f for f in findings if f.subject == "set:capability-usage"]
        self.assertEqual(len(usage), 1)
        self.assertIs(usage[0].severity, Severity.NOTE)
        self.assertLess(usage[0].evidence["capabilitiesUsed"], VOCAB.capability_count)

    def test_the_metric_reports_median_max_and_singleton_share(self) -> None:
        finding = [f for f in self._run_metric()
                   if f.subject == "set:capability+higher-thresholds"][0]
        for key in ("median", "max", "singletons", "singletonSharePermille", "medianMax"):
            self.assertIn(key, finding.evidence)

    def test_an_empty_set_population_reports_NOT_MEASURED_never_a_pass(self) -> None:
        findings = CellOccupancy().run(Ctx(corpus=Corpus(), adapter=None))
        self.assertEqual([f.severity for f in findings], [Severity.NOT_MEASURED])

    def test_a_median_above_the_ceiling_is_a_GAP(self) -> None:
        clones = [{"thresholds": [{"pieces": 2, "capability": {"family": "atom.x"}},
                                  {"pieces": 4, "atoms": [{"family": "atom.might"}]}]}
                  for _ in range(TUNING.median_cell_occupancy_max + 1)]
        report = cells.cell_report(clones)
        self.assertFalse(report.within(TUNING.median_cell_occupancy_max))

    def test_the_gate_is_unpromoted_and_the_promotion_trigger_is_written_down(self) -> None:
        """⚠ `gates = False` today because the threshold is defined over the GENERATED species-set
        population, which does not exist. The trigger is recorded rather than remembered."""
        self.assertFalse(CellOccupancy.gates)
        self.assertIn("generation run", PROMOTION_TRIGGER)

    def _run_metric(self):
        corpus = Corpus.load(ITEMS_ROOT)
        registry = MetricRegistry()
        registry.register(CellOccupancy())
        return run_all(registry, Ctx(corpus=corpus, adapter=None))


