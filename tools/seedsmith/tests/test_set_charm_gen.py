class VocabularyTests(unittest.TestCase):
    def test_the_capability_vocabulary_is_60_picks_and_the_stat_vocabulary_is_242(self) -> None:
        """Both counted from `data/seed/items/affix-families/*.json`, not transcribed. The spec's
        own arithmetic: 39 element-free + 3x7 variant = 60; 2 + 31x7 + 23 stat.modify = 242."""
        self.assertEqual(VOCAB.capability_count, 60)
        self.assertEqual(VOCAB.stat_count, 242)

    def test_the_pick_counts_are_reproduced_from_the_families_rather_than_asserted(self) -> None:
        families = vocab_mod.load_families()
        self.assertEqual(len(families), 98)
        caps = [f for f in families if f["kindId"] in TUNING.capability_kinds]
        stats = [f for f in families if f["kindId"] in TUNING.stat_kinds]
        self.assertEqual(len(caps), 42)
        self.assertEqual(len(stats), 56)
        variant = [f for f in caps
                   if (f.get("variants") or {}).get("generate") == TUNING.variant_generator]
        self.assertEqual(len(variant), 3)
        self.assertEqual(len(caps) - len(variant) + len(variant) * TUNING.variant_expansion, 60)

    def test_a_family_whose_kind_is_neither_capability_nor_stat_is_refused_not_dropped(self) -> None:
        with self.assertRaises(ValueError) as caught:
            vocab_mod.build(TUNING, directory=self._one_family_dir("atom.invented", "widget.kind"))
        self.assertIn("classify it before generating", str(caught.exception))

    def test_capability_families_carry_roles_and_that_narrows_the_legal_pool(self) -> None:
        """Mitigation #2 in the spec, and the thing that stops the picker collapsing onto the
        three or four most flattering capabilities.

        ⛔ **Measured, and it does NOT hold uniformly.** Every one of the 60 capability picks
        carries a `roles` list (none is unrestricted), and the narrowing is real for most roles —
        `retinue` reaches 7 of 60, `footing` 13. But **`jewel-minor-a` reaches all 60**: it is the
        universal capability host in the shipped corpus, so a set that claims a minor jewel gets
        the whole pool back and mitigation #2 does no work for it. The first draft of this test
        assumed narrowing everywhere and failed; corrected against the data rather than the data
        being read as wrong."""
        self.assertEqual(sum(1 for p in VOCAB.capability if not p.roles), 0)
        self.assertLess(len(VOCAB.capability_for_roles(["retinue"])), VOCAB.capability_count)
        self.assertLess(len(VOCAB.capability_for_roles(["footing"])), VOCAB.capability_count)
        self.assertEqual(len(VOCAB.capability_for_roles(["jewel-minor-a"])),
                         VOCAB.capability_count)

    def _one_family_dir(self, family_id: str, kind_id: str) -> Path:
        tmp = Path(self.enterContext(__import__("tempfile").TemporaryDirectory()))
        (tmp / "x.json").write_text(json.dumps({
            "kind": "affix-family",
            "entries": [{"id": family_id, "kindId": kind_id, "powerBand": "low"}],
        }), encoding="utf-8")
        return tmp


